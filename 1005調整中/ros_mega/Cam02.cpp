#include "Cam02.h"


//============================================================
// コンストラクタ
//============================================================

Cam::Cam(uint8_t id)
{
    this->id = id;

    state = CAM_IDLE;

    targetPos = 0;

    startTime = 0;
}


//============================================================
// 初期化
//============================================================

void Cam::begin()
{
    // STS3215用シリアル
    //
    // Mega側で
    // Serial1.begin(1000000);
    // を先に実行しておく
    //
    servo.pSerial = &Serial1;
}


//============================================================
// 手動操作
// 正方向へ1段階進める
//============================================================

void Cam::up()
{
    // 補充位置へ戻している途中は
    // 手動操作を受け付けない
    if (state == CAM_RELOADING)
    {
        return;
    }


    // 現在位置を取得
    int currentPos = servo.ReadPos(id);


    // 通信失敗
    if (currentPos == -1)
    {
        return;
    }


    //========================================================
    // 目標位置を計算
    //========================================================

    targetPos =
        currentPos +
        (CAM_STEP * CAM_DIRECTION);


    //========================================================
    // 位置範囲を制限
    //========================================================

    if (targetPos > MAX_POS)
    {
        targetPos = MAX_POS;
    }

    if (targetPos < MIN_POS)
    {
        targetPos = MIN_POS;
    }


    //========================================================
    // サーボへ移動指令
    //========================================================

    servo.WritePosEx(
        id,
        targetPos,
        CAM_SPEED,
        ACC
    );


    //========================================================
    // 状態
    //========================================================

    startTime = millis();

    state = CAM_MOVING;
}


//============================================================
// 手動操作
// 逆方向へ1段階戻す
//============================================================

void Cam::down()
{
    // 補充位置へ戻している途中は
    // 手動操作を受け付けない
    if (state == CAM_RELOADING)
    {
        return;
    }


    // 現在位置を取得
    int currentPos = servo.ReadPos(id);


    // 通信失敗
    if (currentPos == -1)
    {
        return;
    }


    //========================================================
    // 目標位置を計算
    //========================================================

    targetPos =
        currentPos -
        (CAM_STEP * CAM_DIRECTION);


    //========================================================
    // 位置範囲を制限
    //========================================================

    if (targetPos > MAX_POS)
    {
        targetPos = MAX_POS;
    }

    if (targetPos < MIN_POS)
    {
        targetPos = MIN_POS;
    }


    //========================================================
    // サーボへ移動指令
    //========================================================

    servo.WritePosEx(
        id,
        targetPos,
        CAM_SPEED,
        ACC
    );


    //========================================================
    // 状態
    //========================================================

    startTime = millis();

    state = CAM_MOVING;
}


//============================================================
// 自動操作
// 補充位置へ戻す
//============================================================

void Cam::reload()
{
    // すでに補充位置へ移動中なら
    // 新しい指令を出さない
    if (state == CAM_RELOADING)
    {
        return;
    }


    //========================================================
    // 補充位置へ移動
    //========================================================

    servo.WritePosEx(
        id,
        RELOAD_POS,
        CAM_SPEED,
        ACC
    );


    //========================================================
    // 状態
    //========================================================

    targetPos = RELOAD_POS;

    startTime = millis();

    state = CAM_RELOADING;
}


//============================================================
// 状態更新
//============================================================

void Cam::update()
{
    //========================================================
    // 停止中
    //========================================================

    if (state == CAM_IDLE)
    {
        return;
    }


    //========================================================
    // 現在位置を取得
    //========================================================

    int currentPos = servo.ReadPos(id);


    //========================================================
    // 通信失敗
    //========================================================

    if (currentPos == -1)
    {
        // 通信できない場合は
        // 動作中状態を解除する
        state = CAM_IDLE;

        return;
    }


    //========================================================
    // 目標位置へ到達したか
    //========================================================

    if (abs(currentPos - targetPos)
        <= POSITION_TOLERANCE)
    {
        state = CAM_IDLE;

        return;
    }


    //========================================================
    // タイムアウト
    //========================================================

    if (millis() - startTime >= CAM_TIMEOUT)
    {
        state = CAM_IDLE;

        return;
    }
}


//============================================================
// 動作中か
//============================================================

bool Cam::isMoving()
{
    return state != CAM_IDLE;
}


//============================================================
// 補充位置にいるか
//============================================================

bool Cam::isReloadPosition()
{
    // 現在位置を取得
    int currentPos = servo.ReadPos(id);


    // 通信失敗
    if (currentPos == -1)
    {
        return false;
    }


    //========================================================
    // 補充位置との距離を確認
    //========================================================

    return
        abs(currentPos - RELOAD_POS)
        <= POSITION_TOLERANCE;
}