#ifndef CAM02_H
#define CAM02_H

#include <Arduino.h>
#include <SCServo.h>


class Cam
{
public:

    //============================================================
    // コンストラクタ
    //============================================================

    Cam(uint8_t id);


    //============================================================
    // 初期化
    //============================================================

    void begin();


    //============================================================
    // 手動カム操作
    //============================================================

    // 正方向へ1段階進める
    //
    // ボタンを押している間、繰り返し呼び出す
    //
    void up();


    // 逆方向へ1段階戻す
    //
    // ボタンを押している間、繰り返し呼び出す
    //
    void down();


    //============================================================
    // 自動カム操作
    //============================================================

    // 補充位置へ戻す
    //
    // Aボタンによる補充動作などで使用
    //
    void reload();


    //============================================================
    // 状態更新
    //============================================================

    // 毎loop()呼び出す
    void update();


    //============================================================
    // 状態確認
    //============================================================

    // 現在カムが動作中か
    //
    // true  = 動作中
    // false = 停止
    //
    bool isMoving();


    // 現在カムが補充位置にいるか
    //
    // true  = 補充位置
    // false = 補充位置ではない
    //
    bool isReloadPosition();


private:

    //============================================================
    // STS3215
    //============================================================

    SMS_STS servo;

    // サーボID
    uint8_t id;


    //============================================================
    // カム位置
    //============================================================

    // 補充位置
    const int RELOAD_POS = 1900;


    //============================================================
    // 手動操作
    //============================================================

    // up() / down() 1回で進む位置
    const int CAM_STEP = 50;


    //============================================================
    // サーボ設定
    //============================================================

    // サーボ速度
    const int CAM_SPEED = 4090;

    // 加速度
    const int ACC = 50;


    //============================================================
    // 位置判定
    //============================================================

    // 目標位置との許容誤差
    const int POSITION_TOLERANCE = 20;


    //============================================================
    // タイムアウト
    //============================================================

    // サーボ動作の最大待ち時間
    const unsigned long CAM_TIMEOUT = 1000;


    //============================================================
    // サーボ位置範囲
    //============================================================

    const int MIN_POS = 0;
    const int MAX_POS = 4095;


    //============================================================
    // 回転方向
    //============================================================

    // 実機で方向が逆だった場合
    //
    // 1  → 正方向
    // -1 → 逆方向
    //
    const int CAM_DIRECTION = 1;


    //============================================================
    // カム状態
    //============================================================

    enum CamState
    {
        CAM_IDLE,       // 停止中
        CAM_MOVING,     // 手動操作中
        CAM_RELOADING   // 補充位置へ移動中
    };


    // 現在の状態
    CamState state;


    //============================================================
    // 目標位置
    //============================================================

    int targetPos;


    //============================================================
    // 動作開始時刻
    //============================================================

    unsigned long startTime;
};


#endif