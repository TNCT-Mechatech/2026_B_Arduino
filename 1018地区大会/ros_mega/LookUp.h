#ifndef LookUp_H
#define LookUp_H

#include <Arduino.h>
#include <SCServo.h>


//============================================================
// LookUp
//
// STS3046を使用した射出機構の角度調整
//
// 機能
//   ・up()        : 射出角度を上方向へ1段階動かす
//   ・down()      : 射出角度を下方向へ1段階動かす
//   ・update()    : サーボの移動状態を監視
//   ・isMoving()  : 現在移動中か確認
//   ・isPosition(): 上側の位置にいるか確認
//
// リミットスイッチは使用しない
// サーボの現在位置(ReadPos)から位置を判断する
//============================================================

class LookUp
{
public:

    //========================================================
    // コンストラクタ
    //========================================================

    LookUp(uint8_t id);


    //========================================================
    // 初期化
    //========================================================

    // Serial1をSTS3046との通信に使用
    //
    // Serial1.begin(1000000);
    // はMega側のsetup()などで先に実行する
    void begin();


    //========================================================
    // 手動角度調整
    //========================================================

    // 射出角度を上方向へ1段階動かす
    void up();

    // 射出角度を下方向へ1段階動かす
    void down();


    //========================================================
    // 状態更新
    //========================================================

    // 毎loop()呼び出す
    //
    // ・目標位置に到達したか
    // ・通信できているか
    // ・タイムアウトしたか
    // を確認する
    void update();


    //========================================================
    // 状態確認
    //========================================================

    // サーボが現在移動中か
    //
    // true  = 移動中
    // false = 停止
    bool isMoving();


    // 上側の位置にいるか
    //
    // true  = 上側の基準位置付近
    // false = それ以外
    //
    // リミットスイッチは使用せず、
    // STS3046のReadPos()から判断する
    bool isPosition();


private:

    //========================================================
    // STS3046
    //========================================================

    SMS_STS servo;

    // サーボID
    //
    // 今回使用するSTS3046
    // ID = 23
    uint8_t id;


    //========================================================
    // 手動操作
    //========================================================

    // up() / down() 1回で移動する位置
    //
    // 現在値：20
    //
    // 【調整方法】
    // ReadPos()で現在位置を確認し、
    // up() / down()を1回実行した後に
    // どれだけ位置が変化したか確認する。
    //
    // 例：
    // 2000 → 2020
    // ならSTEP = 20
    const int LookUp_STEP = 50;


    //========================================================
    // サーボ位置範囲
    //========================================================

    // ソフトウェア上の下限位置
    //
    // 現在値：0
    //
    // 【調整方法】
    // 実機を下方向へゆっくり動かし、
    // 機械的にこれ以上動かしたくない位置の
    // ReadPos()を確認する。
    //
    // その値をMIN_POSに設定する。
    //
    // ※機械的にぶつかる前に余裕を持たせる。
    const int MIN_POS = 620;


    // ソフトウェア上の上限位置
    //
    // 現在値：4095
    //
    // 【調整方法】
    // 実機を上方向へゆっくり動かし、
    // 機械的にこれ以上動かしたくない位置の
    // ReadPos()を確認する。
    //
    // その値をMAX_POSに設定する。
    //
    // ※機械的にぶつかる前に余裕を持たせる。
    const int MAX_POS = 1800;


    //========================================================
    // 上側位置判定
    //========================================================

    // 「上側にいる」と判断する基準位置
    //
    // 現在値：仮で3000
    //
    // 【調整方法】
    //
    // 1. 実機を目的の「上側位置」まで動かす
    //
    // 2. ReadPos()で現在位置を確認
    //
    // 3. その値をPOSITION_POSに設定
    //
    // 例：
    //
    // 上側位置でReadPos() = 3000
    //
    // → POSITION_POS = 3000
    const int POSITION_POS = 600;


    // 上側位置と判断する許容誤差
    //
    // 現在値：20
    //
    // 例：
    //
    // POSITION_POS = 3000
    // TOLERANCE   = 20
    //
    // 2980 ～ 3020
    // ↓
    // isPosition() == true
    //
    // 【調整方法】
    // 実機の停止位置のばらつきを確認する。
    //
    // 位置のばらつきが大きい場合は増やす。
    // 判定を厳しくしたい場合は減らす。
    const int POSITION_TOLERANCE = 20;


    //========================================================
    // サーボ設定
    //========================================================

    // サーボ速度
    //
    // 現在値：2000
    //
    // 【調整方法】
    // 実機でup() / down()を動かして、
    //
    // ・速すぎないか
    // ・遅すぎないか
    // ・機構に衝撃が出ないか
    //
    // を確認する。
    const int LookUp_SPEED = 4000;


    // 加速度
    //
    // 現在値：50
    //
    // 【調整方法】
    // 動き始め・停止時の衝撃を確認する。
    //
    // 必要に応じて変更する。
    const int ACC = 100;


    //========================================================
    // タイムアウト
    //========================================================

    // 目標位置へ到達するまでの最大時間 [ms]
    //
    // 現在値：1000 ms
    //
    // 【調整方法】
    //
    // 1. 実際にup() / down()を実行する
    //
    // 2. 目標位置へ到達するまでの時間を測る
    //
    // 3. 実測値より少し長い時間を設定する
    //
    // 例：
    //
    // 実測 350 ms
    // → TIMEOUT = 500～700 ms程度
    //
    // あまり短くすると、
    // 正常に動いているのにタイムアウトする。
    const unsigned long LookUp_TIMEOUT = 1000;


    //========================================================
    // 状態
    //========================================================

    enum LookUpState
    {
        LookUp_IDLE,       // 停止中
        LookUp_MOVING      // 移動中
    };


    // 現在の状態
    LookUpState state;


    //========================================================
    // 目標位置
    //========================================================

    int targetPos;


    //========================================================
    // 動作開始時刻
    //========================================================

    unsigned long startTime;
};


#endif