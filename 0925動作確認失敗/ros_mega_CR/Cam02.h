#ifndef CAM02_H
#define CAM02_H

#include <Arduino.h>
#include <SCServo.h>

class Cam
{
public:
    Cam(uint8_t id);

    void begin();

    //============================================================
    // 装填カム角度調整
    //============================================================

    // 正方向へ1ステップ進める
    void up();

    // 逆方向へ1ステップ戻す
    void down();

    // 補充位置へ戻す
    void reload();

    // 補充中、補充位置を維持する
    void holdReload();

    // 毎loop()呼び出す
    void update();

    // 現在動作中か
    bool isMoving();

    // 補充位置にいるか
    bool isAtReload();

    // 補充中のカムロック
    void setReloadLock(bool lock);

private:

    SMS_STS servo;

    uint8_t id;

    //============================================================
    // カム位置
    //============================================================

    // TODO:
    // 実機で補充位置を調整したら変更する
    const int RELOAD_POS = 800;

    // 1回の角度調整量
    const int CAM_STEP = 20;

    // サーボ速度
    const int CAM_SPEED = 200;

    // 加速度
    const int ACC = 50;

    // 目標位置との許容誤差
    const int POSITION_TOLERANCE = 20;

    //============================================================
    // サーボ位置範囲
    //
    // 0～4095で1周分
    // これ以上は回転させない
    //============================================================

    const int MIN_POS = 0;
    const int MAX_POS = 4095;

    //============================================================
    // カム回転方向
    //
    // 実機確認後、
    // UP/DOWNが逆なら -1 に変更
    //============================================================

    const int CAM_DIRECTION = 1;

    //============================================================
    // タイムアウト
    //============================================================

    const unsigned long CAM_TIMEOUT = 1000;

    //============================================================
    // 補充位置維持
    //
    // 補充中は負荷によってカムがずれる可能性があるため、
    // 一定間隔で800を再指令する
    //============================================================

    const unsigned long RELOAD_HOLD_INTERVAL = 100;

    //============================================================
    // 状態
    //============================================================

    enum CamState
    {
        CAM_IDLE,
        CAM_MOVING,
        CAM_RELOADING
    };

    CamState state;

    // 現在の目標位置
    int targetPos;

    // 動作開始時刻
    unsigned long startTime;

    // 補充位置維持のための前回指令時刻
    unsigned long lastHoldTime;

    // 補充中の操作ロック
    bool reloadLock;
};

#endif